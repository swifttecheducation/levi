#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
engines/adobe/ae_script_generator.py — Tự động sinh kịch bản ExtendScript (.jsx) cho Adobe After Effects.
Tạo Composition 1080x1920 chuẩn 9:16, tự động đưa text Hook và Subtitles vào timeline,
áp dụng biểu thức chuyển động chuyên nghiệp (Expressions: Inertial Bounce đàn hồi, Smooth Wiggle).
"""

import os
import json
from typing import List, Dict, Any, Optional


# Biểu thức nảy đàn hồi (Inertial Bounce Expression) chuẩn ngành Motion Graphics After Effects
INERTIAL_BOUNCE_EXPRESSION = """
// Inertial Bounce for Scale / Position
n = 0;
if (numKeys > 0){
  n = nearestKey(time).index;
  if (key(n).time > time){ n--; }
}
if (n == 0){ t = 0; } else { t = time - key(n).time; }
if (n > 0 && t < 1){
  v = velocityAtTime(key(n).time - ((thisComp.frameDuration)?thisComp.frameDuration:0.03));
  amp = 0.05; freq = 3.5; decay = 5.0;
  value + (v/100)*amp*Math.sin(freq*t*2*Math.PI)/Math.exp(decay*t);
} else { value; }
""".strip()


class AfterEffectsScriptGenerator:
    def __init__(
        self,
        comp_name: str = "Levi_Motion_Comp",
        width: int = 1080,
        height: int = 1920,
        fps: int = 30,
        duration_sec: float = 30.0
    ):
        self.comp_name = comp_name
        self.width = width
        self.height = height
        self.fps = fps
        self.duration_sec = duration_sec

    def generate_jsx_script(
        self,
        hook_text: str,
        subtitles: List[Dict[str, Any]],
        brand_colors: Dict[str, str],
        headline_font: str = "PlayfairDisplay-Bold",
        caption_font: str = "BeVietnamPro-Bold",
        output_jsx_path: str = "render_ae.jsx"
    ) -> str:
        """
        Sinh mã nguồn JavaScript ExtendScript (.jsx) cho Adobe After Effects.
        """
        # Chuyển đổi mã màu hex (#RRGGBB) sang float mảng 0..1 cho AE
        def hex_to_ae(hex_str: str):
            h = hex_str.lstrip("#")
            return [int(h[0:2], 16)/255.0, int(h[2:4], 16)/255.0, int(h[4:6], 16)/255.0]

        primary_rgb = hex_to_ae(brand_colors.get("primary", "#F2EDE4"))
        highlight_rgb = hex_to_ae(brand_colors.get("highlight", "#720000"))

        subs_json_escaped = json.dumps(subtitles, ensure_ascii=False)

        jsx_code = f"""// Auto-generated by Levi Super Studio v4.0 for Adobe After Effects
app.beginUndoGroup("Create Levi Studio Reel");

var comp = app.project.items.addComp(
    "{self.comp_name}",
    {self.width},
    {self.height},
    1.0,
    {self.duration_sec},
    {self.fps}
);

// 1. Hook Title Layer
var hookLayer = comp.layers.addText("{hook_text.replace('"', '\\"')}");
var hookProp = hookLayer.property("Source Text");
var hookDoc = hookProp.value;
hookDoc.fontSize = 72;
hookDoc.font = "{headline_font}";
hookDoc.fillColor = [{primary_rgb[0]}, {primary_rgb[1]}, {primary_rgb[2]}];
hookDoc.justification = ParagraphJustification.CENTER_JUSTIFY;
hookProp.setValue(hookDoc);

// Đặt vị trí Hook ở 1/3 trên màn hình (y ~ 450)
hookLayer.property("Position").setValue([{self.width / 2}, 450]);

// Keyframe Scale nảy bật (0% -> 100% trong 0.4s)
var scaleProp = hookLayer.property("Scale");
scaleProp.setValueAtTime(0.0, [0, 0]);
scaleProp.setValueAtTime(0.4, [100, 100]);
scaleProp.expression = `{INERTIAL_BOUNCE_EXPRESSION}`;

// Hook hiển thị trong 5 giây đầu
hookLayer.outPoint = Math.min({self.duration_sec}, 5.5);

// 2. Chèn các phân đoạn Subtitles né cằm
var subsData = {subs_json_escaped};
for (var i = 0; i < subsData.length; i++) {{
    var s = subsData[i];
    var subLayer = comp.layers.addText(s.text);
    var subProp = subLayer.property("Source Text");
    var subDoc = subProp.value;
    subDoc.fontSize = 46;
    subDoc.font = "{caption_font}";
    subDoc.fillColor = [{primary_rgb[0]}, {primary_rgb[1]}, {primary_rgb[2]}];
    subDoc.justification = ParagraphJustification.CENTER_JUSTIFY;
    subProp.setValue(subDoc);

    // Neo dưới cằm (y = 1320)
    subLayer.property("Position").setValue([{self.width / 2}, 1320]);
    subLayer.inPoint = s.start;
    subLayer.outPoint = s.end;
}}

app.endUndoGroup();
"""
        os.makedirs(os.path.dirname(os.path.abspath(output_jsx_path)), exist_ok=True)
        with open(output_jsx_path, "w", encoding="utf-8") as f:
            f.write(jsx_code)

        return output_jsx_path
